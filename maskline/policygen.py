"""Generate a deterministic policy draft YAML from the latest scan findings.

The draft is rendered as plain text (never via a YAML dumper) so that the
same findings always produce byte-identical output: tables and columns are
sorted, no wall-clock value is embedded, and floats are formatted fixed.
"""

from __future__ import annotations

import json
import re
import shutil
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from .config import Paths
from .policies import _parse_policy  # same-package reuse of the strict loader
from .registry import Catalog, DatasetInventory, inspect_dataset
from .utils import MasklineError, atomic_write_text

# Concrete transformer per sensitive type, mirroring policies/example.yaml.
TRANSFORM_BY_TYPE: dict[str, tuple[str, dict[str, Any]]] = {
    "id_card": ("mask", {"keep_prefix": 2, "keep_suffix": 2}),
    "credit_code": ("mask", {"keep_prefix": 2, "keep_suffix": 4}),
    "bank_card": ("mask", {"keep_prefix": 4, "keep_suffix": 4}),
    "mobile_phone": ("mask", {"keep_prefix": 3, "keep_suffix": 4}),
    "email": ("hash", {}),
    "ipv4": ("mask", {"keep_prefix": 0, "keep_suffix": 0}),
    "person_name": ("pseudonym", {}),
    "address": ("generalize", {"mode": "address"}),
}

# Findings with any other confidence ("none") never reach the draft.
_ACTIONABLE_CONFIDENCE = ("high", "medium", "low")

_POLICY_DESCRIPTION = (
    "Draft generated by `maskline genpolicy` from the latest scan findings; "
    "review TODO(confirm) columns before production use."
)


@dataclass(frozen=True)
class ColumnDraft:
    table: str
    column: str
    sensitive_type: str
    confidence: str
    score: float
    transformer: str
    params: dict[str, Any]
    review: str  # "" (high), "review" (medium), "confirm" (low / unmapped type)


@dataclass(frozen=True)
class DraftResult:
    output_path: Path
    backup_path: Path | None
    policy_name: str
    table_count: int
    column_count: int
    confirm_count: int


def plan_drafts(findings: list[dict[str, Any]]) -> list[ColumnDraft]:
    """Map findings to column drafts, sorted by (table, column)."""
    drafts: list[ColumnDraft] = []
    for finding in findings:
        confidence = str(finding.get("confidence") or "none")
        sensitive_type = finding.get("sensitive_type")
        if confidence not in _ACTIONABLE_CONFIDENCE or not sensitive_type:
            continue
        sensitive_type = str(sensitive_type)
        mapped = TRANSFORM_BY_TYPE.get(sensitive_type)
        if mapped is None or confidence == "low":
            # Unknown type or weak evidence: fall back to the most
            # conservative transform and require manual confirmation.
            transformer, params, review = "nullify", {}, "confirm"
        else:
            transformer, params = mapped
            params = dict(params)
            review = "review" if confidence == "medium" else ""
        drafts.append(
            ColumnDraft(
                table=str(finding["table_name"]),
                column=str(finding["column_name"]),
                sensitive_type=sensitive_type,
                confidence=confidence,
                score=float(finding.get("score") or 0.0),
                transformer=transformer,
                params=params,
                review=review,
            )
        )
    drafts.sort(key=lambda draft: (draft.table, draft.column))
    return drafts


def _comment_for(draft: ColumnDraft) -> str:
    detail = f"{draft.sensitive_type} (score={draft.score:.2f})"
    if draft.review == "confirm":
        if draft.sensitive_type not in TRANSFORM_BY_TYPE:
            return f"TODO(confirm): unmapped sensitive type {detail}; conservative nullify"
        return f"TODO(confirm): low confidence {detail}; conservative nullify"
    if draft.review == "review":
        return f"review: medium confidence {detail}"
    return f"{draft.confidence}: {detail}"


_BARE_SCALAR = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")
_RESERVED_WORDS = {"true", "false", "null", "yes", "no", "on", "off", "~"}


def _yaml_string(value: str) -> str:
    """Bare scalar when unambiguous, else a JSON double-quoted YAML scalar."""
    if _BARE_SCALAR.match(value) and value.lower() not in _RESERVED_WORDS:
        return value
    return json.dumps(value, ensure_ascii=False)


def _yaml_param_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return _yaml_string(str(value))


def render_draft(
    inventory: DatasetInventory, drafts: list[ColumnDraft], policy_name: str
) -> str:
    lines = [
        "# Generated by `maskline genpolicy` from the latest scan findings.",
        f"# Dataset: {inventory.path.name}  fingerprint: {inventory.fingerprint}",
        "# Columns marked TODO(confirm) need manual review before production use.",
        "version: 1",
        f"name: {_yaml_string(policy_name)}",
        f"description: {_yaml_string(_POLICY_DESCRIPTION)}",
        "datasets:",
        f"  - path: {_yaml_string(inventory.path.name)}",
        "    tables:",
    ]
    current_table = None
    for draft in drafts:  # already sorted by (table, column)
        if draft.table != current_table:
            current_table = draft.table
            lines.append(f"      {_yaml_string(current_table)}:")
            lines.append("        columns:")
        key = _yaml_string(draft.column)
        comment = _comment_for(draft)
        if draft.params:
            lines.append(f"          {key}:  # {comment}")
            lines.append(f"            transformer: {draft.transformer}")
            params = ", ".join(
                f"{name}: {_yaml_param_value(value)}"
                for name, value in draft.params.items()
            )
            lines.append(f"            params: {{ {params} }}")
        else:
            lines.append(f"          {key}: {draft.transformer}  # {comment}")
    return "\n".join(lines) + "\n"


def _backup_existing(target: Path) -> Path:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    candidate = target.with_name(f"{target.name}.{stamp}.bak")
    counter = 2
    while candidate.exists():
        candidate = target.with_name(f"{target.name}.{stamp}.{counter}.bak")
        counter += 1
    shutil.copy2(target, candidate)
    return candidate


def generate_policy_draft(
    dataset_path: str | Path,
    output_path: str | Path,
    paths: Paths,
    *,
    force: bool = False,
) -> DraftResult:
    """Write a policy draft for one dataset from its latest scan findings."""
    inventory = inspect_dataset(dataset_path)
    if not paths.meta_db.is_file():
        raise MasklineError(
            f"no scan findings found at {paths.meta_db}; "
            "run `maskline scan` on the dataset first"
        )
    with Catalog(paths.meta_db) as catalog:
        findings = catalog.findings_for(inventory.fingerprint)
    if not findings:
        raise MasklineError(
            f"no scan findings recorded for {inventory.path.name} "
            f"(fingerprint {inventory.fingerprint[:16]}...); run `maskline scan` "
            "first — the dataset may have changed since the last scan"
        )
    drafts = plan_drafts(findings)
    if not drafts:
        raise MasklineError(
            f"scan findings for {inventory.path.name} contain no sensitive "
            "columns; nothing to generate"
        )
    policy_name = f"draft-{inventory.path.stem}"
    text = render_draft(inventory, drafts, policy_name)
    # Self-check before writing anything: the draft must pass the same strict
    # parsing and dataset validation the executor applies at load time.
    policy = _parse_policy(yaml.safe_load(text), Path(output_path))
    policy.validate_against(inventory)
    output = Path(output_path)
    backup_path = None
    if output.exists() or output.is_symlink():
        if not output.is_file():
            raise MasklineError(f"output path is not a regular file: {output}")
        if not force:
            raise MasklineError(
                f"output file exists: {output} "
                "(use --force to overwrite; the old file is backed up first)"
            )
        backup_path = _backup_existing(output)
    atomic_write_text(output, text)
    return DraftResult(
        output_path=output,
        backup_path=backup_path,
        policy_name=policy_name,
        table_count=len({draft.table for draft in drafts}),
        column_count=len(drafts),
        confirm_count=sum(1 for draft in drafts if draft.review == "confirm"),
    )
